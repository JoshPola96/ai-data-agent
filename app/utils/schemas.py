class AgentStep(BaseModel):
    """Agent reasoning trace step"""

    type: str  # "reasoning" | "tool_call" | "tool_result"
    content: Optional[str] = None
    tool_name: Optional[str] = None
    tool_args: Optional[Dict] = None
    tool_result: Optional[str] = None


# session_id lands in Redis keys, so the charset is restricted rather than trusted. Shared
# by every endpoint that takes one: /upload validated nothing while /chat validated this,
# so a file could be uploaded under an id that could never be asked a question.
SESSION_ID_PATTERN = r"^[A-Za-z0-9_\-]+$"


class ChatRequest(BaseModel):
    session_id: Optional[str] = Field(
        None,
        max_length=_limits.MAX_SESSION_ID_CHARS,
        pattern=SESSION_ID_PATTERN,
    )
    query: str = Field(..., min_length=1, max_length=_limits.MAX_QUERY_CHARS)
    use_rag: bool = True
    model: Optional[str] = Field(None, max_length=64)


class ChatResponse(BaseModel):
    session_id: str
    response: str
    sources: List[str] = []
    metadata: Dict = {}
    agent_trace: List[AgentStep] = []


class UploadResponse(BaseModel):
    status: str
    session_id: str
    filename: str
    doc_id: str
    text_chunks: int
    dataframes: int


class FileInfo(BaseModel):
    filename: str
    doc_id: str
    uploaded_at: str
    text_chunks: int
    dataframes: int
    file_type: str


class ModelInfo(BaseModel):
    name: str
    provider: str
    is_default: bool = False


class ChatTurn(BaseModel):
    user: str
    assistant: str
    timestamp: str


class SessionStats(BaseModel):
    session_id: str
    chat_turns: int
    dataframes: int
    documents: int
    document_list: List[str] = []


class HistoryResponse(BaseModel):
    session_id: str
    history: List[ChatTurn]
    stats: SessionStats
